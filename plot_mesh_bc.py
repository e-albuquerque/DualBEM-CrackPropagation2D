"""
Pre-processing visualization script for Fracture 2D (Dual-BEM) input data.

Reads `<id>_input_data.txt` generated by `fracture_2d.exe` and plots:
  - Quadratic boundary elements (including curved and discontinuous elements)
  - Crack surfaces (automatically detected from coincident opposite-oriented elements)
  - Boundary nodes and internal points
  - Boundary conditions (Dirichlet displacements in red, Neumann tractions in blue,
    and elastic springs in green), with scaled quiver arrows for non-zero values.

Based on the visualization conventions of `preproc.py` (BEM2D_elastostatic).
"""

import argparse
from pathlib import Path
import re
import numpy as np
import matplotlib.pyplot as plt
from matplotlib.collections import LineCollection


def parse_input_data(filepath):
    """
    Parses a Fracture 2D `<id>_input_data.txt` file and returns a dictionary
    with problem metadata, boundary elements, boundary points, BCs, and internal points.
    """
    filepath = Path(filepath)
    if not filepath.is_file():
        raise FileNotFoundError(f"Arquivo nao encontrado: {filepath}")

    data = {
        "analysis_name": filepath.stem,
        "problem_type": "",
        "E": None,
        "nu": None,
        "be_num": 0,
        "bn_num": 0,
        "in_num": 0,
        "elem_ends": [],
        "elem_lambdas": [],
        "elem_incid": [],
        "b_nodes": [],
        "bc_types": [],
        "bc_vals": [],
        "int_points": [],
    }

    section = "HEADER"

    with filepath.open("r", encoding="utf-8", errors="replace") as f:
        for raw_line in f:
            line = raw_line.strip()
            if not line or line.startswith("*"):
                continue

            # Section transitions
            if line.startswith("Boundary Elements:"):
                section = "ELEM_WAIT"
                continue
            if line.startswith("Boundary Points:"):
                section = "BN_WAIT"
                continue
            if line.startswith("Internal Points:"):
                section = "IN_WAIT"
                continue

            if section == "HEADER":
                if line.startswith("Analysis name:"):
                    data["analysis_name"] = line.split("Analysis name:", 1)[1].strip()
                elif "Plane stress" in line or "Plane strain" in line:
                    data["problem_type"] = line.rstrip(".")
                elif line.startswith("Elasticity modulus"):
                    data["E"] = float(line.split("=", 1)[1].strip())
                elif line.startswith("Poisson ratio"):
                    data["nu"] = float(line.split("=", 1)[1].strip())
                elif line.startswith("Number of boundary elements"):
                    data["be_num"] = int(line.split("=", 1)[1].strip())
                elif line.startswith("Number of boundary points"):
                    data["bn_num"] = int(line.split("=", 1)[1].strip())
                elif line.startswith("Number of internal points"):
                    data["in_num"] = int(line.split("=", 1)[1].strip())

            elif section == "ELEM_WAIT":
                if line.startswith("Elem.") and "X1" in line:
                    section = "ELEM_COORDS"
                elif line.startswith("Elem.") and "Lambda 1" in line:
                    section = "ELEM_INCID"

            elif section == "ELEM_COORDS":
                if line.startswith("Elem.") and "Lambda 1" in line:
                    section = "ELEM_INCID"
                    continue
                parts = line.split()
                if len(parts) >= 5:
                    # elem_id, X1, Y1, X2, Y2
                    data["elem_ends"].append([float(parts[1]), float(parts[2]),
                                              float(parts[3]), float(parts[4])])

            elif section == "ELEM_INCID":
                parts = line.split()
                if len(parts) >= 6:
                    # elem_id, lambda1, lambda2, node1, node2, node3
                    data["elem_lambdas"].append([float(parts[1]), float(parts[2])])
                    data["elem_incid"].append([int(parts[3]) - 1,
                                               int(parts[4]) - 1,
                                               int(parts[5]) - 1])

            elif section == "BN_WAIT":
                if line.startswith("Point"):
                    section = "BOUNDARY_POINTS"

            elif section == "BOUNDARY_POINTS":
                parts = line.split()
                if len(parts) >= 7:
                    # point_id, X, Y, bc1, val1, bc2, val2
                    data["b_nodes"].append([float(parts[1]), float(parts[2])])
                    data["bc_types"].append((parts[3], parts[5]))
                    data["bc_vals"].append([float(parts[4]), float(parts[6])])

            elif section == "IN_WAIT":
                if line.startswith("Point"):
                    section = "INTERNAL_POINTS"

            elif section == "INTERNAL_POINTS":
                parts = line.split()
                if len(parts) >= 3:
                    data["int_points"].append([float(parts[1]), float(parts[2])])

    data["elem_ends"] = np.array(data["elem_ends"], dtype=np.float64)
    data["elem_lambdas"] = np.array(data["elem_lambdas"], dtype=np.float64)
    data["elem_incid"] = np.array(data["elem_incid"], dtype=np.int64)
    data["b_nodes"] = np.array(data["b_nodes"], dtype=np.float64)
    data["bc_vals"] = np.array(data["bc_vals"], dtype=np.float64)
    data["int_points"] = (np.array(data["int_points"], dtype=np.float64)
                          if data["int_points"] else np.zeros((0, 2), dtype=np.float64))

    return data


def comp_xyplot(elem_ends, elem_incid, b_nodes, npp=11):
    """
    Interpolates coordinates along each quadratic boundary element for plotting.

    Uses the geometric endpoints (X1, Y1) at eta=-1, (X2, Y2) at eta=+1, and
    the element middle boundary node (incid[1]) at eta=0 with standard quadratic
    shape functions N1, N2, N3.
    """
    eta = np.linspace(-1.0, 1.0, npp)
    num_elements = elem_ends.shape[0]

    xplot = np.zeros((num_elements, npp), dtype=np.float64)
    yplot = np.zeros((num_elements, npp), dtype=np.float64)

    n1 = 0.5 * eta * (eta - 1.0)
    n2 = 1.0 - eta ** 2
    n3 = 0.5 * eta * (eta + 1.0)

    for i in range(num_elements):
        x1, y1, x2, y2 = elem_ends[i]
        mid_idx = elem_incid[i, 1]
        xm, ym = b_nodes[mid_idx, 0], b_nodes[mid_idx, 1]

        xplot[i, :] = n1 * x1 + n2 * xm + n3 * x2
        yplot[i, :] = n1 * y1 + n2 * ym + n3 * y2

    return xplot, yplot


def detect_crack_elements(elem_ends, elem_lambdas, elem_incid, b_nodes):
    """
    Detects Dual-BEM crack face elements by checking for coincident
    opposite-oriented discontinuous element pairs.
    """
    num_elements = elem_ends.shape[0]
    is_crack = np.zeros(num_elements, dtype=bool)
    if num_elements == 0:
        return is_crack

    all_x = np.concatenate([elem_ends[:, 0], elem_ends[:, 2]])
    all_y = np.concatenate([elem_ends[:, 1], elem_ends[:, 3]])
    diag = np.hypot(np.max(all_x) - np.min(all_x), np.max(all_y) - np.min(all_y))
    tol = max(diag * 1e-6, 1e-12)

    mids = b_nodes[elem_incid[:, 1]]

    for i in range(num_elements):
        if elem_lambdas[i, 0] > 0.99 and elem_lambdas[i, 1] > 0.99:
            continue
        p1_i = elem_ends[i, 0:2]
        p2_i = elem_ends[i, 2:4]
        mid_i = mids[i]
        for j in range(i + 1, num_elements):
            if np.hypot(*(mid_i - mids[j])) > tol:
                continue
            p1_j = elem_ends[j, 0:2]
            p2_j = elem_ends[j, 2:4]
            opposite = (np.hypot(*(p1_i - p2_j)) <= tol and np.hypot(*(p2_i - p1_j)) <= tol)
            same_dir = (np.hypot(*(p1_i - p1_j)) <= tol and np.hypot(*(p2_i - p2_j)) <= tol)
            if opposite or same_dir:
                is_crack[i] = True
                is_crack[j] = True

    return is_crack


def compute_node_local_frames(data):
    """
    Computes outward unit normal (nx, ny) and unit tangent (tx, ty) at each
    boundary node based on the element geometry and intrinsic coordinate
    (-lambda1, 0, +lambda2).
    """
    bn_num = len(data["b_nodes"])
    normals = np.zeros((bn_num, 2), dtype=np.float64)
    tangents = np.zeros((bn_num, 2), dtype=np.float64)

    elem_ends = data["elem_ends"]
    elem_lambdas = data["elem_lambdas"]
    elem_incid = data["elem_incid"]
    b_nodes = data["b_nodes"]

    for i in range(len(elem_ends)):
        x1, y1, x2, y2 = elem_ends[i]
        xm, ym = b_nodes[elem_incid[i, 1]]
        l1, l2 = elem_lambdas[i]
        etas = (-l1, 0.0, l2)

        for local_k, n_idx in enumerate(elem_incid[i]):
            eta = etas[local_k]
            dn1 = eta - 0.5
            dn2 = -2.0 * eta
            dn3 = eta + 0.5
            dxdeta = dn1 * x1 + dn2 * xm + dn3 * x2
            dydeta = dn1 * y1 + dn2 * ym + dn3 * y2
            jac = np.hypot(dxdeta, dydeta)
            if jac > 0.0:
                tx = dxdeta / jac
                ty = dydeta / jac
                nx = dydeta / jac
                ny = -dxdeta / jac
                tangents[n_idx] = [tx, ty]
                normals[n_idx] = [nx, ny]

    return normals, tangents


def extract_bc_vectors(data):
    """
    Extracts boundary condition masks and global (vx, vy) vectors per BC kind
    ('disp', 'trac', 'sprg') and DOF component (1 and 2).
    """
    bn_num = len(data["b_nodes"])
    normals, tangents = compute_node_local_frames(data)

    kinds = ("disp", "trac", "sprg")
    # For each kind and DOF index (0 or 1), store boolean mask and global vector (vx, vy)
    bc_masks = {k: [np.zeros(bn_num, dtype=bool), np.zeros(bn_num, dtype=bool)] for k in kinds}
    bc_vecs = {k: [np.zeros((bn_num, 2), dtype=np.float64),
                   np.zeros((bn_num, 2), dtype=np.float64)] for k in kinds}
    has_local_nt = {k: [False, False] for k in kinds}
    has_global_xy = {k: [False, False] for k in kinds}

    for idx, (t1, t2) in enumerate(data["bc_types"]):
        v1, v2 = data["bc_vals"][idx]
        for dof, (btype, val) in enumerate(((t1, v1), (t2, v2))):
            if "_" not in btype:
                continue
            prefix, axis = btype.split("_", 1)
            if prefix not in bc_masks:
                continue
            bc_masks[prefix][dof][idx] = True

            if axis == "x":
                has_global_xy[prefix][dof] = True
                bc_vecs[prefix][dof][idx] = [val, 0.0]
            elif axis == "y":
                has_global_xy[prefix][dof] = True
                bc_vecs[prefix][dof][idx] = [0.0, val]
            elif axis == "n":
                has_local_nt[prefix][dof] = True
                bc_vecs[prefix][dof][idx] = val * normals[idx]
            elif axis == "t":
                has_local_nt[prefix][dof] = True
                bc_vecs[prefix][dof][idx] = val * tangents[idx]

    return bc_masks, bc_vecs, has_global_xy, has_local_nt


def show_geometry(data, xplot, yplot, is_crack_elem, save_path,
                  dpi=300, show_nodes=True, show_plot=False):
    """
    Visualizes the Fracture 2D quadratic mesh, crack faces, internal points,
    and boundary conditions, saving the figure to `save_path`.

    Color and marker convention matching `preproc.py`:
      - Boundary elements: black solid curves
      - Crack faces: dark orange solid curves (if present)
      - Dirichlet BCs (disp): red markers ('rx' / 'rP') and red arrows
      - Neumann BCs (trac): blue markers ('bx' / 'bP') and blue arrows
      - Spring BCs (sprg): green markers ('gx' / 'gP') and green arrows
      - Internal points: forestgreen dots (if present)
    """
    b_nodes = data["b_nodes"]
    int_points = data["int_points"]

    # Determine bounding box from element endpoints, boundary nodes, and internal points
    pts_x = [data["elem_ends"][:, 0], data["elem_ends"][:, 2], b_nodes[:, 0]]
    pts_y = [data["elem_ends"][:, 1], data["elem_ends"][:, 3], b_nodes[:, 1]]
    if len(int_points) > 0:
        pts_x.append(int_points[:, 0])
        pts_y.append(int_points[:, 1])

    all_x = np.concatenate(pts_x)
    all_y = np.concatenate(pts_y)
    x_min, x_max = np.min(all_x), np.max(all_x)
    y_min, y_max = np.min(all_y), np.max(all_y)
    delta_x = x_max - x_min
    delta_y = y_max - y_min
    max_delta = max(delta_x, delta_y) if max(delta_x, delta_y) > 0 else 1.0

    bc_masks, bc_vecs, has_global_xy, has_local_nt = extract_bc_vectors(data)

    fig, ax = plt.subplots(figsize=(8, 6.5))
    ax.grid(True, linestyle="--", alpha=0.4)

    # 1. Plot boundary elements (black) and crack faces (darkorange)
    boundary_segs = [list(zip(xplot[i], yplot[i]))
                     for i in range(len(xplot)) if not is_crack_elem[i]]
    crack_segs = [list(zip(xplot[i], yplot[i]))
                  for i in range(len(xplot)) if is_crack_elem[i]]

    if boundary_segs:
        lc_bound = LineCollection(
            boundary_segs,
            linestyles="solid",
            colors="black",
            linewidths=1.0,
            label="Boundary elements",
            zorder=2,
        )
        ax.add_collection(lc_bound)

    if crack_segs:
        lc_crack = LineCollection(
            crack_segs,
            linestyles="solid",
            colors="darkorange",
            linewidths=2.0,
            label="Crack faces",
            zorder=6,
        )
        ax.add_collection(lc_crack)

    # 2. Plot internal points (if present)
    if len(int_points) > 0:
        ax.plot(
            int_points[:, 0], int_points[:, 1],
            "o", color="forestgreen", markersize=3.0, alpha=0.8,
            label=f"Internal points ({len(int_points)})",
            zorder=2,
        )

    # 3. Plot quiver arrows for non-zero BCs (resultant per physical BC kind)
    styles = {
        "trac": {"color": "blue", "markers": ("bx", "bP"),
                 "labels": (r"Known $t_x$", r"Known $t_y$"),
                 "nt_labels": (r"Known $t_n$", r"Known $t_t$"),
                 "mix_labels": (r"Known $t_x / t_n$", r"Known $t_y / t_t$"), "zorder": 4},
        "sprg": {"color": "green", "markers": ("gx", "gP"),
                 "labels": (r"Spring $k_x$", r"Spring $k_y$"),
                 "nt_labels": (r"Spring $k_n$", r"Spring $k_t$"),
                 "mix_labels": (r"Spring $k_x / k_n$", r"Spring $k_y / k_t$"), "zorder": 4},
        "disp": {"color": "red", "markers": ("rx", "rP"),
                 "labels": (r"Known $u_x$", r"Known $u_y$"),
                 "nt_labels": (r"Known $u_n$", r"Known $u_t$"),
                 "mix_labels": (r"Known $u_x / u_n$", r"Known $u_y / u_t$"), "zorder": 5},
    }

    for kind in ("trac", "sprg", "disp"):
        st = styles[kind]
        vecs_total = bc_vecs[kind][0] + bc_vecs[kind][1]
        mags = np.hypot(vecs_total[:, 0], vecs_total[:, 1])
        max_val = np.max(mags) if len(mags) else 0.0

        if max_val > 1e-15:
            arrow_scale = 10.0 * max_val / max_delta
            nz = np.where((bc_masks[kind][0] | bc_masks[kind][1]) & (mags > 1e-15))[0]
            if len(nz) > 0:
                ax.quiver(
                    b_nodes[nz, 0], b_nodes[nz, 1],
                    vecs_total[nz, 0], vecs_total[nz, 1],
                    color=st["color"], angles="xy", scale_units="xy",
                    scale=arrow_scale, width=0.0035, headaxislength=3.5,
                    zorder=st["zorder"],
                )

    # 4. Plot BC node markers (Neumann first, Spring next, Dirichlet last so corners stand out)
    if show_nodes:
        for kind in ("trac", "sprg", "disp"):
            st = styles[kind]
            for dof in (0, 1):
                idx = np.where(bc_masks[kind][dof])[0]
                if len(idx) > 0:
                    if has_global_xy[kind][dof] and has_local_nt[kind][dof]:
                        lbl = st["mix_labels"][dof]
                    elif has_local_nt[kind][dof]:
                        lbl = st["nt_labels"][dof]
                    else:
                        lbl = st["labels"][dof]
                    msize = 5.0 if dof == 0 else 3.8
                    ax.plot(
                        b_nodes[idx, 0], b_nodes[idx, 1],
                        st["markers"][dof], markersize=msize,
                        label=lbl, zorder=st["zorder"] + 0.5,
                    )

    # 5. Formatting, margins, legend, and export
    pad_x = 0.15 * delta_x if delta_x > 0 else 0.15 * max_delta
    pad_y = 0.15 * delta_y if delta_y > 0 else 0.15 * max_delta
    ax.set_aspect("equal")
    ax.set_xlim(x_min - pad_x, x_max + pad_x)
    ax.set_ylim(y_min - pad_y, y_max + pad_y)
    ax.set_xlabel("x")
    ax.set_ylabel("y")

    subtitle_parts = []
    if data["problem_type"]:
        subtitle_parts.append(data["problem_type"])
    subtitle_parts.append(f"{data['be_num']} elem, {data['bn_num']} nodes")
    if len(int_points) > 0:
        subtitle_parts.append(f"{len(int_points)} int. pts")

    ax.set_title(f"{data['analysis_name']}\n({' | '.join(subtitle_parts)})", fontsize=11)

    handles, labels = ax.get_legend_handles_labels()
    if handles:
        ax.legend(
            handles, labels,
            loc="upper left",
            bbox_to_anchor=(1.02, 1.0),
            borderaxespad=0.0,
            fontsize=8.5,
            framealpha=0.9,
        )

    save_path = Path(save_path)
    save_path.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(save_path, dpi=dpi, bbox_inches="tight")
    print(f"Mesh and boundary conditions plot saved to '{save_path}'.")

    if show_plot:
        plt.show()
    plt.close(fig)


def default_output_path(input_path):
    """Derives `<id>_mesh_bc.png` from `<id>_input_data.txt`."""
    p = Path(input_path)
    name = p.name
    if name.endswith("_input_data.txt"):
        out_name = re.sub(r"_input_data\.txt$", "_mesh_bc.png", name)
    else:
        out_name = f"{p.stem}_mesh_bc.png"
    return p.with_name(out_name)


def main():
    parser = argparse.ArgumentParser(
        description="Plot Fracture 2D (<id>_input_data.txt) mesh and boundary conditions to PNG."
    )
    parser.add_argument(
        "input_file",
        help="Path to the `<id>_input_data.txt` file generated by fracture_2d.",
    )
    parser.add_argument(
        "-o", "--output",
        default=None,
        help="Output PNG file path (default: `<id>_mesh_bc.png` alongside input_file).",
    )
    parser.add_argument(
        "--dpi",
        type=int,
        default=300,
        help="Output image resolution in DPI (default: 300).",
    )
    parser.add_argument(
        "--no-nodes",
        action="store_true",
        help="Hide boundary node BC markers and show only mesh, crack, and non-zero arrows.",
    )
    parser.add_argument(
        "--show",
        action="store_true",
        help="Display the interactive matplotlib window after saving.",
    )

    args = parser.parse_args()
    out_path = args.output if args.output is not None else default_output_path(args.input_file)

    data = parse_input_data(args.input_file)
    xplot, yplot = comp_xyplot(data["elem_ends"], data["elem_incid"], data["b_nodes"])
    is_crack_elem = detect_crack_elements(
        data["elem_ends"], data["elem_lambdas"], data["elem_incid"], data["b_nodes"]
    )

    n_crack_pairs = int(np.sum(is_crack_elem)) // 2
    print(
        f"Parsed '{args.input_file}': {data['be_num']} boundary elements "
        f"({n_crack_pairs} crack element pairs), {data['bn_num']} boundary points, "
        f"{len(data['int_points'])} internal points."
    )

    show_geometry(
        data,
        xplot,
        yplot,
        is_crack_elem,
        save_path=out_path,
        dpi=args.dpi,
        show_nodes=not args.no_nodes,
        show_plot=args.show,
    )


if __name__ == "__main__":
    main()
